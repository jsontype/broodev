  // 'ko-KR' → ko · 'zh-TW'/'zh-Hant-HK' → zh-Hant · 'zh'/'zh-CN' → zh · 'pt-BR' → pt · 미지원 → null
  function norm(tag) {
    tag = String(tag || '').toLowerCase();
    if (!tag) return null;
    if (tag.indexOf('zh') === 0) return /hant|tw|hk|mo/.test(tag) ? 'zh-Hant' : 'zh';
    var p = tag.split('-')[0];
    return LANGS.indexOf(p) >= 0 ? p : null;
  }

  function detect() {
    var saved = null;
    try { saved = localStorage.getItem('mh:lang'); } catch (e) { /* 프라이빗 모드 등 */ }
    if (LANGS.indexOf(saved) >= 0) return saved;
    var q = /[?&]lang=([A-Za-z-]+)/.exec(root.location ? root.location.search : '');
    if (q && norm(q[1])) return norm(q[1]);
    // 브라우저 선호 언어 목록에서 첫 매치 (없으면 en)
    var nav = root.navigator || {};
    var cands = nav.languages && nav.languages.length ? nav.languages : [nav.language];
    for (var i = 0; i < cands.length; i++) { var l = norm(cands[i]); if (l) return l; }
    return 'en';
  }

  var cur = detect();

  function t(key, vars) {
    var s = D[cur] && D[cur][key] != null ? D[cur][key] : (D.en[key] != null ? D.en[key] : key);
    if (vars) s = s.replace(/\{(\w+)\}/g, function (_, k) { return vars[k] != null ? vars[k] : ''; });
    return s;
  }

  function each(sel, fn) { Array.prototype.forEach.call(document.querySelectorAll(sel), fn); }

  function apply() {
    document.documentElement.lang = HTML_LANG[cur] || cur;
    // <title>·meta description: <body data-page="xlsx|pptx|pricing|contact|404"> 가 있고 title_*/desc_* 키가 있으면 그것, 없으면 공통 title/meta_desc
    var page = document.body ? document.body.getAttribute('data-page') : null;
    document.title = t(page && D.en['title_' + page] != null ? 'title_' + page : 'title');
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t(page && D.en['desc_' + page] != null ? 'desc_' + page : 'meta_desc'));
    // 공유용 og:/twitter: 제목·설명도 같은 언어로(크롤러는 정적 값을 보지만, 화면 안 문서와 어긋나지 않게)
    each('meta[property="og:title"], meta[name="twitter:title"]', function (m) { m.setAttribute('content', document.title); });
    if (md) each('meta[property="og:description"], meta[name="twitter:description"]', function (m) { m.setAttribute('content', md.getAttribute('content')); });
    each('[data-i18n]', function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    each('[data-i18n-html]', function (el) { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    ['title', 'placeholder', 'aria-label'].forEach(function (attr) {
      each('[data-i18n-' + attr + ']', function (el) { el.setAttribute(attr, t(el.getAttribute('data-i18n-' + attr))); });
    });
    each('[data-lang-current]', function (el) { el.textContent = NAMES[cur]; });
    each('[data-lang]', function (el) { el.classList.toggle('active', el.getAttribute('data-lang') === cur); });
    try { document.dispatchEvent(new CustomEvent('mh:lang', { detail: cur })); } catch (e) { /* 구형 브라우저 */ }
  }

  function set(lang) {
    if (LANGS.indexOf(lang) < 0) return;
    cur = lang;
    try { localStorage.setItem('mh:lang', lang); } catch (e) { /* 저장 못 해도 이번 세션은 적용 */ }
    apply();
  }

  // 헤더 언어 풀다운 항목(LANGS 순서). href 는 ?lang= 변형 URL — 클릭은 app.js/site.js 가 가로채 저장·전환하고, 크롤러에는 hreflang 변형으로 통하는 실제 링크
  var menu = document.getElementById('pg-lang-menu');
  if (menu && !menu.children.length) {
    LANGS.forEach(function (l) {
      var li = document.createElement('li'), a = document.createElement('a');
      a.href = '?lang=' + l; a.setAttribute('role', 'option'); a.setAttribute('data-lang', l); a.setAttribute('lang', HTML_LANG[l] || l); a.textContent = NAMES[l];
      li.appendChild(a); menu.appendChild(li);
    });
  }

  root.MH_I18N = { t: t, apply: apply, set: set, lang: function () { return cur; }, LANGS: LANGS, NAMES: NAMES };
